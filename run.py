import matplotlib
matplotlib.use("Agg")
import matplotlib.dates
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from src import config, crosssection, dataset, fetch, model

OUT = Path(__file__).resolve().parent / "results"


def opening_table(raw: dict, levels: pd.DataFrame) -> pd.DataFrame:
    """First trade on D0 against the last pre-event print. Description only."""
    d0, pre = pd.Timestamp(config.D0), pd.Timestamp(config.PRE_EVENT)
    rows = []
    for t in ("DI1F29", "DI1F35"):
        di = dataset._di(raw[t])
        rows.append({"asset": t, "unit": "bp", "pre_print": "settlement 23/10",
                     "pre": di.at[pre, "level"], "d0_open": di.at[d0, "open"],
                     "d0_close": di.at[d0, "close"], "d0_settle": di.at[d0, "level"],
                     "open_move": (di.at[d0, "open"] - di.at[pre, "level"]) * 100,
                     "settle_move": (di.at[d0, "level"] - di.at[pre, "level"]) * 100})
    dol = raw["DOL"].assign(trade_date=pd.to_datetime(raw["DOL"]["trade_date"]))
    front = levels.at[d0, "dol_front"]
    f = dol[dol["ticker"] == front].set_index("trade_date")
    rows.append({"asset": f"USDBRL ({front})", "unit": "log %", "pre_print": "settlement 23/10",
                 "pre": f.at[pre, "settlement_price"], "d0_open": f.at[d0, "open_px"],
                 "d0_close": f.at[d0, "close_px"], "d0_settle": f.at[d0, "settlement_price"],
                 "open_move": 100 * np.log(f.at[d0, "open_px"] / f.at[pre, "settlement_price"]),
                 "settle_move": 100 * np.log(f.at[d0, "settlement_price"] / f.at[pre, "settlement_price"])})
    b = raw["BOVA11"].assign(trade_date=pd.to_datetime(raw["BOVA11"]["trade_date"])).set_index("trade_date")
    rows.append({"asset": "BOVA11 (Ibovespa proxy for the open)", "unit": "log %", "pre_print": "close 23/10",
                 "pre": b.at[pre, "close"], "d0_open": b.at[d0, "open"], "d0_close": b.at[d0, "close"],
                 "d0_settle": np.nan,
                 "open_move": 100 * np.log(b.at[d0, "open"] / b.at[pre, "close"]),
                 "settle_move": 100 * np.log(b.at[d0, "close"] / b.at[pre, "close"])})
    return pd.DataFrame(rows)


def chart(event: pd.DataFrame, moves: pd.DataFrame, asset: str, unit_scale: float, unit: str):
    e = event[(event.asset == asset) & (event.factors == "core") & (event.est_end == "spec")
              & (event.window == config.MAIN_WINDOW)]
    if e.empty:
        return
    hist = moves.loc[:pd.Timestamp(config.D0), asset].tail(80) * unit_scale
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 3.6), gridspec_kw={"width_ratios": [2, 1]})
    a1.bar(hist.index, hist.values, color="#8aa1bf", width=1.0)
    a1.axhline(0, color="#333", lw=0.6)
    a1.set_title(f"{asset}: daily move, last 80 sessions ({unit})", fontsize=10)
    a1.xaxis.set_major_formatter(matplotlib.dates.DateFormatter("%d/%m"))
    x = np.arange(len(e))
    a2.bar(x - 0.27, e.observed * unit_scale, 0.27, label="observed", color="#1f4e8c")
    a2.bar(x, e.predicted * unit_scale, 0.27, label="predicted", color="#9db4d6")
    a2.bar(x + 0.27, e.residual * unit_scale, 0.27, label="residual", color="#b0322a")
    a2.set_xticks(x, e.day)
    a2.axhline(0, color="#333", lw=0.6)
    a2.set_title("Event days, core model, 252d to 23/10", fontsize=10)
    a2.legend(fontsize=8, frameon=False)
    fig.tight_layout()
    (OUT / "charts").mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / "charts" / f"{asset}.png", dpi=130)
    plt.close(fig)


def _fmt(asset, v):
    return f"{v:+.1f} bp" if config.ASSETS[asset]["kind"] == "rate" else f"{100 * v:+.2f}%"


def write_results_md(event, opening, top, moves, pending, xs, two_day, interventions):
    main = event[(event.factors == "core") & (event.est_end == "spec")
                 & (event.window == config.MAIN_WINDOW)]
    lines = ["# Results", "",
             "Generated by `run.py`. Descriptive only: a residual is the move the global "
             "factors do not account for. It is not the causal effect of the election.", "",
             "## D0 (26/10 against 23/10), core model, 252 sessions to 23/10", "",
             "| Asset | Observed | Predicted | Residual | Residual / sd (OOS) | Residual / largest earlier error | R² | Source |",
             "|---|---|---|---|---|---|---|---|"]
    src = {"DI1F29": "SILO-BZ, B3 Price Report", "DI1F35": "SILO-BZ, B3 Price Report",
           "USDBRL": "SILO-BZ, B3 Price Report (DOL front)", "IBOV": "SILO-BZ, B3 index statistics",
           "NTNB35": "Tesouro Transparente (Tesouro Direto)",
           "PRE720": "SILO-BZ, B3 reference curve PRE", "PRE2520": "SILO-BZ, B3 reference curve PRE"}
    for _, r in main[main.day == "D0"].iterrows():
        lines.append(f"| {config.ASSETS[r.asset]['label']} | {_fmt(r.asset, r.observed)} | "
                     f"{_fmt(r.asset, r.predicted)} | {_fmt(r.asset, r.residual)} | "
                     f"{r.resid_over_sd_oos:+.1f} | {r.x_largest_prior:.1f}x (history since "
                     f"{r.oos_history_start}) | {r.r2:.2f} | {src[r.asset]} |")
    lines += ["", "Factors: ΔUST10Y (bp), Δ(UST10Y − UST2Y) (bp), S&P 500 log return. "
              f"Not yet published for D0: {', '.join(pending) or 'none'}.", "",
              "## Robustness: residual / sd (OOS) on D0", "",
              "| Asset | " + " | ".join(f"{e} {w}d" for e in config.EST_ENDS for w in config.WINDOWS)
              + " | +VIX | +lag-1 factors | +Brent |",
              "|---|" + "---|" * (len(config.EST_ENDS) * len(config.WINDOWS) + 3)]
    d0 = event[event.day == "D0"]
    for a in main.asset.unique():
        cells = []
        for e in config.EST_ENDS:
            for w in config.WINDOWS:
                v = d0[(d0.asset == a) & (d0.factors == "core") & (d0.est_end == e) & (d0.window == w)]
                cells.append(f"{v.resid_over_sd_oos.iloc[0]:+.1f}" if len(v) else "—")
        for fs in ("core_vix", "core_lag1", "core_brent"):
            v = d0[(d0.asset == a) & (d0.factors == fs) & (d0.est_end == "spec") & (d0.window == config.MAIN_WINDOW)]
            cells.append(f"{v.resid_over_sd_oos.iloc[0]:+.1f}" if len(v) else "—")
        lines.append(f"| {a} | " + " | ".join(cells) + " |")
    lines += ["", "## Clock-matched check: 2-session change, 23/10 to 27/10", "",
              "Each asset and factor is measured at the same two dates, so Tesouro Direto morning "
              "rates and B3 settlements cover the same span. The span includes D+1: Treasury "
              "buybacks and the fiscal statement of 27/10 are inside it.", "",
              "| Asset | Observed | Predicted | Residual | Residual / sd (OOS) | Residual / largest earlier error |",
              "|---|---|---|---|---|---|"]
    for _, r in two_day.iterrows():
        lines.append(f"| {r.asset} | {_fmt(r.asset, r.observed)} | {_fmt(r.asset, r.predicted)} | "
                     f"{_fmt(r.asset, r.residual)} | {r.resid_over_sd_oos:+.1f} | {r.x_largest_prior:.1f}x |")
    lines += ["", "## Interventions and same-day news", "",
              "Flags are per date, from `docs/interventions.csv` (sources there). A flag marks a day "
              "on which the residual also contains the event; it does not measure it.", "",
              "| Date | Kind | Event | Confirmed |", "|---|---|---|---|"]
    for _, r in interventions.iterrows():
        lines.append(f"| {r.date} | {r.kind} | {r.description} | {r.confirmed} |")
    post = main[main.day != "D0"]
    lines += ["", "## Reversal after D0", ""]
    if post.empty:
        lines.append("No session after D0 is loaded yet. Rerun `python run.py --refresh` once 27/10 to 29/10 land.")
    else:
        lines += ["| Asset | Day | Observed | Residual | Cumulative residual | Share of D0 residual reversed | Flags |",
                  "|---|---|---|---|---|---|---|"]
        for _, r in post.iterrows():
            lines.append(f"| {r.asset} | {r.day} | {_fmt(r.asset, r.observed)} | {_fmt(r.asset, r.residual)} | "
                         f"{_fmt(r.asset, r.cum_residual)} | {100 * r.reversal_share:.0f}% | {r.intervention} |")
        lines.append("")
        lines.append("The Flags column lists the confirmed interventions of that day. Do not read a reversal as a change of view on a flagged day.")
    lines += ["", "## Opening gap on D0 (first trade, description only)", "",
              "| Asset | 23/10 print | D0 open | D0 close | D0 settlement | Move at open | Move at settlement or close |",
              "|---|---|---|---|---|---|---|"]
    for _, r in opening.iterrows():
        u = "bp" if r.unit == "bp" else "%"
        lines.append(f"| {r.asset} | {r.pre} ({r.pre_print}) | {r.d0_open} | {r.d0_close} | "
                     f"{'' if pd.isna(r.d0_settle) else r.d0_settle} | {r.open_move:+.1f} {u} | {r.settle_move:+.1f} {u} |")
    lines += ["", "## Largest earlier residuals (core, 252d, history to 23/10)", "",
              "| Asset | Date | Residual |", "|---|---|---|"]
    for _, r in top[top.est_end == "spec"].iterrows():
        lines.append(f"| {r.asset} | {r.date} | {_fmt(r.asset, r.residual)} |")
    fr = moves.loc["2026-10-05":"2026-10-23"]
    lines += ["", "## Context: first round to runoff (observed sums, no model)", "",
              "| Asset | 05/10 (first session after the first round) | 05/10 to 23/10 | 26/10 (D0) |",
              "|---|---|---|---|"]
    for a in main.asset.unique():
        lines.append(f"| {a} | {_fmt(a, moves.at[pd.Timestamp('2026-10-05'), a])} | "
                     f"{_fmt(a, fr[a].sum())} | {_fmt(a, moves.at[pd.Timestamp(config.D0), a])} |")
    lines += ["", "## Exporters versus domestic stocks (log returns from the 23/10 close, no model)", "",
              "Groups fixed before looking at returns: exporters = privately controlled, mostly USD revenue; "
              "domestic = B3 consumption, real estate and small-cap indices; state-controlled kept apart.", "",
              "| Name | Group | Day | Return that day | Cumulative | Cumulative vs Ibovespa | Cumulative in USD |",
              "|---|---|---|---|---|---|---|"]
    for _, r in xs.sort_values(["day", "group", "name"]).iterrows():
        lines.append(f"| {r['name']} | {r.group} | {r.day} | {100 * r.ret_day:+.2f}% | {100 * r.ret_cum:+.2f}% | "
                     f"{100 * r.ret_cum_vs_ibov:+.2f}% | {100 * r.ret_cum_usd:+.2f}% |")
    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true", help="re-download every input")
    ap.add_argument("--no-tesouro", action="store_true")
    ap.add_argument("--through", default=date.today().isoformat())
    args = ap.parse_args()

    raw = fetch.fetch_all(date.fromisoformat(args.through), args.refresh, not args.no_tesouro)
    moves, levels = dataset.build(raw)
    for f in config.CORE_FACTORS:
        moves[f"{f}_lag1"] = moves[f].shift(1)

    d0 = pd.Timestamp(config.D0)
    factor_sets = {"core": config.CORE_FACTORS,
                   "core_vix": (*config.CORE_FACTORS, "d_vix"),
                   "core_lag1": (*config.CORE_FACTORS, *(f"{f}_lag1" for f in config.CORE_FACTORS))}
    pending = [f for f in ("r_brent", "r_usd_broad")
               if d0 not in moves.index or pd.isna(moves.at[d0, f])]
    if "r_brent" not in pending:
        factor_sets["core_brent"] = (*config.CORE_FACTORS, "r_brent")
    if not pending:
        factor_sets["full"] = (*config.CORE_FACTORS, *config.EXTRA_FACTORS)

    assets = [a for a in config.ASSETS if a in moves]
    interventions = pd.read_csv(Path(__file__).resolve().parent / "docs" / "interventions.csv")
    flags = {}
    for _, r in interventions.iterrows():
        d = date.fromisoformat(r["date"])
        flags[d] = "; ".join(filter(None, [flags.get(d, ""), r["kind"]]))
    out = model.run(moves, assets, factor_sets, flags)
    OUT.mkdir(exist_ok=True)
    # The repo is public: S&P 500 and VIX are copyrighted, so their values (and
    # changes derived from them) stay out of the committed CSV. fetch.py
    # rebuilds them.
    licensed = [c for c in moves if c.startswith(("r_spx", "d_vix"))]
    moves.drop(columns=licensed).to_csv(OUT / "inputs_moves.csv", index_label="date")
    out["event"].to_csv(OUT / "event_table.csv", index=False)
    out["coefs"].to_csv(OUT / "coefficients.csv", index=False)
    out["stability"].to_csv(OUT / "stability.csv", index=False)
    top = []
    for (a, fs, end, w), e in out["errors"].items():
        if fs == "core" and w == config.MAIN_WINDOW:
            for day, v in e.abs().nlargest(5).items():
                top.append({"asset": a, "est_end": end, "date": day.date(), "residual": e[day]})
    pd.DataFrame(top).to_csv(OUT / "largest_prior_residuals.csv", index=False)
    opening = opening_table(raw, levels)
    opening.to_csv(OUT / "opening_gap.csv", index=False)

    for a in assets:
        kind = config.ASSETS[a]["kind"]
        chart(out["event"], moves, a, 1.0 if kind == "rate" else 100.0, "bp" if kind == "rate" else "log %")

    xs_raw = crosssection.fetch(date.fromisoformat(args.through), args.refresh)
    # No model here, so B3 sessions do not wait for US data: keep every session
    # that has both an Ibovespa level and a DOL front settlement.
    ibov_b3 = raw["IBOV"].assign(trade_date=pd.to_datetime(raw["IBOV"]["trade_date"])).set_index("trade_date")["level"]
    dol_b3 = dataset._dol_front(raw["DOL"], ibov_b3.index)
    fx_b3 = np.log(dol_b3["level"] / dol_b3["prev_same"]).dropna()
    b3_sessions = ibov_b3.index.intersection(fx_b3.index)
    fx_index = np.exp(fx_b3.reindex(b3_sessions).cumsum())
    xs = crosssection.table(xs_raw, ibov_b3, fx_index, b3_sessions)
    xs.to_csv(OUT / "cross_section.csv", index=False)
    two_day = model.two_day_check(levels, config.TWO_DAY_ASSETS)
    two_day.to_csv(OUT / "two_day_check.csv", index=False)
    write_results_md(out["event"], opening, pd.DataFrame(top), moves, pending, xs, two_day, interventions)

    meta = {
        "run_date": date.today().isoformat(),
        "sessions": [str(moves.index.min().date()), str(moves.index.max().date())],
        "assets": assets,
        "factor_sets": {k: list(v) for k, v in factor_sets.items()},
        "factors_pending_at_d0": pending,
        "tesouro_error": raw.get("TESOURO_ERROR"),
        "post_days_available": [str(d.date()) for d in moves.index if d > d0][: config.POST_DAYS],
    }
    (OUT / "run_meta.json").write_text(json.dumps(meta, indent=2))
    print(json.dumps(meta, indent=2))


if __name__ == "__main__":
    main()
